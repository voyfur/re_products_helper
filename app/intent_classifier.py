def classify_intent(question: str) -> IntentType:
    q = question.lower()
    if _COMBAT_GYM_RE.search(q):
        return IntentType.GYM_STRENGTH_COMBAT
    if _ENDURANCE_RE.search(q):
        return IntentType.ENDURANCE_CARDIO
    if _NUTRITION_RE.search(q):
        return IntentType.NUTRITION_SUPPLEMENTS
    return IntentType.GENERAL_PRODUCT


def enrich_prompt_with_intent(base_prompt: str, intent: IntentType) -> str:
    guidelines = DOMAIN_GUIDELINES.get(intent)
    if not guidelines:
        return base_prompt
    return f"{base_prompt}\n\n{guidelines}"
