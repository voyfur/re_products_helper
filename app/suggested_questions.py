def detect_product_group(product: Product) -> str:
    """Detect specific category key for a Product based on its names and description."""
    search_texts: list[str] = []
    for card in product.languages.values():
        if card.name:
            search_texts.append(card.name)
        if card.description:
            search_texts.append(card.description[:500])
        for attr in card.attributes:
            search_texts.append(f"{attr.name} {attr.value}")

    full_text = " ".join(search_texts)

    for category_key, pattern in _PATTERNS:
        if pattern.search(full_text):
            return category_key

    return "GENERAL_FALLBACK"


def get_suggested_questions(product: Product) -> list[str]:
    """Return exactly 6 targeted questions for the product based on its category."""
    group_key = detect_product_group(product)
    return SUGGESTED_QUESTIONS_MATRIX.get(
        group_key, SUGGESTED_QUESTIONS_MATRIX["GENERAL_FALLBACK"]
    )
